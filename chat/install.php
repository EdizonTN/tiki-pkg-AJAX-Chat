		if ($htaccessContent === false) {
			throw new RuntimeException('Nepodarilo sa prečítať _custom/shared/.htaccess.');
		}
		if (strpos($htaccessContent, 'Bridge-config.php') === false) {
			$htaccessContent = rtrim($htaccessContent)."\n\n".$denyBridgeRule."\n";
			if (file_put_contents($sharedHtaccess, $htaccessContent, LOCK_EX) === false) {
				throw new RuntimeException('Nepodarilo sa zabezpečiť Bridge-config.php pomocou .htaccess.');
			}
		}
		$mzChatInstallerConfig['paths'] = array(
			'chatRootPath' => rtrim($chatRootReal, '/\\').DIRECTORY_SEPARATOR,
			'chatUrlPath' => $chatUrlPath,
			'tikiRootPath' => $tikiRoot,
			'tikiUrlPath' => $tikiUrlPath,
			'bridgeConfigPath' => $bridgeConfigPath
		);
		if (!mzWritePhpConfig($configFile, $mzChatInstallerConfig)) {
			throw new RuntimeException('Nepodarilo sa bezpečne uložiť Chat-config.php.');
		}
		$installer = new CustomAJAXChatInstaller();
		if ($installer->createDataBaseTables()) {
			$resultMessage = 'Hotovo. Chýbajúce chatové tabuľky boli vytvorené. Existujúce tabuľky ani dáta neboli odstránené.';
		} else {
			$resultMessage = 'Chatová databázová schéma už existuje. Cesty a konfigurácia bridge boli aktualizované; tabuľky sa nemenili.';
		}
		$resultClass = 'success';
	} catch (Throwable $e) {
		error_log('Mikrozone chat installer: '.$e->getMessage().' in '.$e->getFile().':'.$e->getLine());
		$resultMessage = 'Inštalácia zlyhala.';
		$errorDetail = get_class($e).': '.$e->getMessage().' ('.basename($e->getFile()).':'.$e->getLine().')';
		foreach (array(
			isset($db['pass']) ? $db['pass'] : '',
			isset($mzChatInstallerConfig['mzChatSharedSecret']) ? $mzChatInstallerConfig['mzChatSharedSecret'] : ''
		) as $sensitiveValue) {
			if (is_string($sensitiveValue) && $sensitiveValue !== '') {
				$errorDetail = str_replace($sensitiveValue, '[REDACTED]', $errorDetail);
			}
		}
		$resultDetail = $errorDetail;
		$resultClass = 'error';
	}

