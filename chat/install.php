function mzInstallerStop($status, $message) {
	http_response_code($status);
	echo '<!doctype html><html lang="sk"><meta charset="utf-8"><title>Mikrozone chat installer</title>';
	echo '<body><main><h1>Mikrozone chat – inštalátor</h1><p>'.htmlspecialchars($message, ENT_QUOTES, 'UTF-8').'</p></main></body></html>';
	exit;
}

function mzFindTikiRoot($startDirectory) {
	$current = realpath($startDirectory);
	if ($current === false) {
		return false;
	}
	while (true) {
		if (is_file($current.DIRECTORY_SEPARATOR.'tiki-setup.php')) {
			return rtrim($current, '/\\').DIRECTORY_SEPARATOR;
		}
		$parent = dirname($current);
		if ($parent === $current) {
			return false;
		}
		$current = $parent;
	}
}

function mzWritePhpConfig($file, array $values) {
	// The installer is allowed to update the existing config file, but must not
	// require write access to lib/ itself. Keep its root:www-data ownership and
	// permissions by writing to the existing inode instead of temp+rename.
	if (!is_file($file) || !is_writable($file)) {
		return false;
	}
	$contents = "<?php\n// Generated by the Mikrozone chat installer.\n".
		"define('AJAX_CHAT_BANNED', 6);\n".
		"define('AJAX_CHAT_CUSTOM', 5);\n".
		"define('AJAX_CHAT_CHATBOT', 4);\n".
		"define('AJAX_CHAT_ADMIN', 3);\n".
		"define('AJAX_CHAT_MODERATOR', 2);\n".
		"define('AJAX_CHAT_USER', 1);\n".
		"define('AJAX_CHAT_GUEST', 0);\n".
		"return ".var_export($values, true).";\n";
	$handle = @fopen($file, 'c+');
	if ($handle === false) {
		return false;
	}
	if (!flock($handle, LOCK_EX)) {
		fclose($handle);
		return false;
	}
	$success = ftruncate($handle, 0) && rewind($handle);
	$offset = 0;
	$length = strlen($contents);
	while ($success && $offset < $length) {
		$written = fwrite($handle, substr($contents, $offset));
		if ($written === false || $written === 0) {
			$success = false;
			break;
		}
		$offset += $written;
	}
	if ($success) {
		$success = fflush($handle);
	}
	flock($handle, LOCK_UN);
	fclose($handle);
	return $success;
}

function mzWriteBridgeConfig($file, array $values) {
	$directory = dirname($file);
	if (!is_dir($directory) || !is_writable($directory)) {
		return false;
	}
	$tempFile = $file.'.tmp.'.bin2hex(random_bytes(6));
	$contents = "<?php\n// Tiki-managed Mikrozone chat bridge settings.\nreturn ".var_export($values, true).";\n";
	if (file_put_contents($tempFile, $contents, LOCK_EX) === false) {
		return false;
	}
	@chmod($tempFile, 0640);
	if (!@rename($tempFile, $file)) {
		@unlink($tempFile);
		return false;
	}
	return true;
}

